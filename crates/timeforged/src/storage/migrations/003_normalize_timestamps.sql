-- Единый формат времени и защита от повторов.
--
-- Метки событий писались тремя разными способами одновременно:
--   2026-03-28T19:52:25+00:00
--   2026-06-04T21:23:00Z
--   2026-03-21T11:20:01.830498377+00:00
-- Это один и тот же момент, записанный по-разному. Пока формат плавает,
-- одно и то же событие невозможно опознать как повтор, а группировки по
-- времени сравнивают строки, а не моменты.
--
-- Приводим всё к секундному UTC (`...Z`) и запрещаем повтор индексом.
-- Секунды достаточно: дебаунс наблюдателя — 30 секунд, поэтому два разных
-- события одного файла в одну секунду не появляются, а два события из
-- разных файлов различаются полем entity.

-- 1. Нормализация. strftime разбирает все три формы и отдаёт одну.
UPDATE events
   SET timestamp = strftime('%Y-%m-%dT%H:%M:%SZ', timestamp)
 WHERE timestamp <> strftime('%Y-%m-%dT%H:%M:%SZ', timestamp)
   AND strftime('%Y-%m-%dT%H:%M:%SZ', timestamp) IS NOT NULL;

-- 2. Повторы, накопившиеся до появления индекса. Оставляем самую раннюю
--    запись группы: у неё меньший id, значит она пришла первой.
DELETE FROM events
 WHERE id NOT IN (
   SELECT MIN(id) FROM events
    GROUP BY user_id, timestamp, event_type, entity
 );

-- 3. Сам запрет. С ним повторная отправка того же события при синхронизации
--    отбрасывается базой, а не полагается на аккуратность вызывающего кода.
CREATE UNIQUE INDEX IF NOT EXISTS idx_events_unique
    ON events(user_id, timestamp, event_type, entity);
